func TestParseResolvConf(t *testing.T) {
	conf := `# Generated by NetworkManager
nameserver 127.0.0.53
nameserver 10.0.0.10
nameserver 10.0.0.10
nameserver fd00::53
nameserver fe80::1%eth0
nameserver not-an-ip
search Corp.Example.com. lab.example.com _msdcs.example.com *.bad
domain corp.example.com
options edns0
`
	r := parseResolvConf(strings.NewReader(conf))
	assert.Equal(t, []string{"10.0.0.10", "fd00::53"}, r.Servers)
	assert.Equal(t, []string{"corp.example.com", "lab.example.com"}, r.SearchDomains)
}

func TestParseResolvConfEmptyAndCapped(t *testing.T) {
	r := parseResolvConf(strings.NewReader(""))
	assert.NotNil(t, r.Servers)
	assert.NotNil(t, r.SearchDomains)

	var b strings.Builder
	b.WriteString("search")
	for i := range 20 {
		b.WriteString(" d" + strings.Repeat("x", i) + ".example.com")
	}
	r = parseResolvConf(strings.NewReader(b.String()))
	assert.Len(t, r.SearchDomains, maxResolverEntries)
}

func TestNormalizeName(t *testing.T) {
	for raw, want := range map[string]string{
		"Corp.Example.COM.": "corp.example.com",
		"lan":               "lan",
		"xn--bcher-kva.ch":  "xn--bcher-kva.ch",
	} {
		got, ok := normalizeName(raw)
		assert.True(t, ok, raw)
		assert.Equal(t, want, got)
	}
	for _, raw := range []string{"", ".", "*.corp.lan", "_ldap._tcp.corp.lan", "-a.corp.lan", "a..b", "a b", "srv.corp.lan/x", strings.Repeat("a", 64) + ".lan"} {
		_, ok := normalizeName(raw)
		assert.False(t, ok, raw)
	}
}
